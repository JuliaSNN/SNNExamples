# Writes STATUS.md and the example table of README.md from scripts/examples.toml and _logs/results.tsv.
#
#   julia --project=. scripts/make_status.jl
#
# Status of an example: pass (ran unchanged), fixed (ran after the changes listed in `changed`), failed, timeout,
# not run (reason given), helper (included by other scripts).

using TOML, Pkg, Dates

const ROOT = normpath(joinpath(@__DIR__, ".."))
examples = TOML.parsefile(joinpath(@__DIR__, "examples.toml"))["example"]

results = Dict{String,NamedTuple}()
resfile = joinpath(ROOT, "_logs", "results.tsv")
if isfile(resfile)
    for l in readlines(resfile)
        f = split(l, '\t'; limit = 5)
        length(f) < 4 && continue
        results[f[1]] = (status = f[2], secs = parse(Float64, f[3]), figs = parse(Int, f[4]), msg = length(f) >= 5 ? f[5] : "")
    end
end

function classify(e)
    st = get(e, "status", "run")
    st == "not run" && return "not run"
    st == "helper" && return "helper"
    r = get(results, e["path"], nothing)
    r === nothing && return "not checked"
    r.status == "pass" && return isempty(get(e, "changed", "")) ? "pass" : "fixed"
    return r.status            # fail or timeout
end

rows = [(e, classify(e)) for e in examples]
counts = Dict{String,Int}()
for (_, s) in rows
    counts[s] = get(counts, s, 0) + 1
end

deps = Pkg.dependencies()
ver(name) = (d = [v for (_, v) in deps if v.name == name]; isempty(d) ? "?" : string(d[1].version))
header = """
SNNModels $(ver("SNNModels")), SpikingNeuralNetworks $(ver("SpikingNeuralNetworks")), SNNUtils $(ver("SNNUtils")), SNNPlots $(ver("SNNPlots")), CairoMakie $(ver("CairoMakie")), Julia $(VERSION)
"""

order = unique(e["topic"] for e in examples)
fmt_secs(s) = s < 60 ? "$(round(Int, s)) s" : "$(round(s / 60; digits = 1)) min"

# ---------------- STATUS.md
open(joinpath(ROOT, "STATUS.md"), "w") do io
    println(io, "# Status of the examples\n")
    println(io, "Generated by `scripts/make_status.jl` from `scripts/examples.toml` and the results of `scripts/run_all.jl`")
    println(io, "($(Dates.format(now(), "yyyy-mm-dd"))). Every example runs in its own process with the CairoMakie PNG backend and a")
    println(io, "timeout of 300 s unless the table says otherwise. Versions: $(strip(header)).\n")
    println(io, "| Status | Meaning | Count |\n|:--|:--|--:|")
    for (s, m) in [("pass", "ran as imported (a header comment was added to each script)"), ("fixed", "ran after the changes listed in the table"),
                   ("failed", "error (first line in the table)"), ("timeout", "no result within the timeout"),
                   ("not run", "not executed, reason in the table"), ("helper", "included by other scripts"),
                   ("not checked", "no result recorded")]
        c = get(counts, s == "failed" ? "fail" : s, 0)
        (c == 0 && s in ("not checked",)) && continue
        println(io, "| $s | $m | $c |")
    end
    println(io, "| total | | $(length(examples)) |\n")
    for topic in order
        println(io, "## $topic\n")
        println(io, "| Script | Status | Time | Figures | Notes |\n|:--|:--|--:|--:|:--|")
        for (e, s) in rows
            e["topic"] == topic || continue
            r = get(results, e["path"], nothing)
            time = (r !== nothing && s in ("pass", "fixed", "fail", "timeout")) ? fmt_secs(r.secs) : ""
            figs = (r !== nothing && s in ("pass", "fixed")) ? string(r.figs) : ""
            extra = isempty(get(e, "note", "")) ? "" : "Observation: " * e["note"]
            note = if s in ("pass", "fixed")
                join(filter(!isempty, [get(e, "changed", ""), extra]), "; ")
            elseif s in ("not run", "helper")
                string(get(e, "reason", ""), isempty(get(e, "changed", "")) ? "" : "; " * e["changed"])
            else
                r === nothing ? "" : r.msg
            end
            tmo = get(e, "timeout", 0) > 0 ? " (timeout $(e["timeout"]) s)" : ""
            println(io, "| `$(e["path"])` | $s$tmo | $time | $figs | $(replace(note, "|" => "\\|")) |")
        end
        println(io)
    end
end

# ---------------- README table
const BEGIN_MARK = "<!-- examples:begin -->"
const END_MARK = "<!-- examples:end -->"
table = IOBuffer()
for topic in order
    println(table, "### $topic\n")
    println(table, "| Example | What it shows | Status |\n|:--|:--|:--|")
    for (e, s) in rows
        e["topic"] == topic || continue
        s == "helper" && continue
        println(table, "| [`$(e["path"])`]($(e["path"])) | $(replace(e["desc"], "|" => "\\|")) | $s |")
    end
    println(table)
end
readme = joinpath(ROOT, "README.md")
txt = read(readme, String)
a = findfirst(BEGIN_MARK, txt)
b = findfirst(END_MARK, txt)
if a !== nothing && b !== nothing
    txt = txt[1:last(a)] * "\n\n" * String(take!(table)) * txt[first(b):end]
    write(readme, txt)
else
    @warn "markers not found in README.md; table not written"
end
println(join(["$k: $v" for (k, v) in sort(collect(counts))], ", "))
